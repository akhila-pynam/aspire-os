"use client";

import React, { useState, useRef } from "react";
import {
  Folder,
  FileCode,
  FileText,
  FileArchive,
  Search,
  HardDrive,
  Cloud,
  Download,
  Trash2,
  Upload,
  Plus,
  Check,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Badge } from "@/components/ui/badge";

interface FileItem {
  id: string;
  name: string;
  type: "folder" | "code" | "document" | "model";
  size: string;
  bytes: number;
  modified: string;
  cloudSynced: boolean;
  content?: string;
}

const initialFiles: FileItem[] = [
  {
    id: "f-1",
    name: "ai-workflows",
    type: "folder",
    size: "4 items",
    bytes: 4096,
    modified: "Today, 06:45",
    cloudSynced: true,
  },
  {
    id: "f-2",
    name: "gemini-3.8-weights.onnx",
    type: "model",
    size: "1.4 GB",
    bytes: 1400000000,
    modified: "Yesterday",
    cloudSynced: true,
  },
  {
    id: "f-3",
    name: "event_dispatch_router.ts",
    type: "code",
    size: "42 KB",
    bytes: 42000,
    modified: "Today, 05:12",
    cloudSynced: true,
    content: "export async function dispatchEvent(stream: any) {\n  console.log('Event streamed');\n}",
  },
  {
    id: "f-4",
    name: "aspire-system-architecture.md",
    type: "document",
    size: "18 KB",
    bytes: 18000,
    modified: "Oct 10, 2026",
    cloudSynced: true,
    content: "# AspireOS Architecture\nNext-gen web desktop with ReactFlow and Recharts.",
  },
  {
    id: "f-5",
    name: "security-audit-report.pdf",
    type: "document",
    size: "820 KB",
    bytes: 820000,
    modified: "Oct 04, 2026",
    cloudSynced: true,
  },
];

export function FilesApp() {
  const [files, setFiles] = useState<FileItem[]>(initialFiles);
  const [searchTerm, setSearchTerm] = useState("");
  const [selectedFile, setSelectedFile] = useState<FileItem | null>(files[2]);
  const [notification, setNotification] = useState<string | null>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);

  const filtered = files.filter((f) =>
    f.name.toLowerCase().includes(searchTerm.toLowerCase())
  );

  const totalBytes = files.reduce((acc, f) => acc + f.bytes, 0);
  const totalMb = (totalBytes / (1024 * 1024)).toFixed(1);

  const showToast = (msg: string) => {
    setNotification(msg);
    setTimeout(() => setNotification(null), 2500);
  };

  const handleFileUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const uploaded = e.target.files?.[0];
    if (!uploaded) return;

    const ext = uploaded.name.split(".").pop()?.toLowerCase();
    let type: FileItem["type"] = "document";
    if (["ts", "js", "json", "py"].includes(ext || "")) type = "code";
    if (["onnx", "bin", "pt"].includes(ext || "")) type = "model";

    const newFile: FileItem = {
      id: `f-${Date.now()}`,
      name: uploaded.name,
      type,
      size: `${(uploaded.size / 1024).toFixed(1)} KB`,
      bytes: uploaded.size,
      modified: "Just now",
      cloudSynced: true,
      content: `Uploaded user file: ${uploaded.name}`,
    };

    setFiles([newFile, ...files]);
    setSelectedFile(newFile);
    showToast(`Uploaded ${uploaded.name} successfully`);
    if (fileInputRef.current) fileInputRef.current.value = "";
  };

  const handleDownloadFile = () => {
    if (!selectedFile) return;

    const content = selectedFile.content || `Content of ${selectedFile.name} generated by AspireOS.`;
    const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = selectedFile.name;
    link.click();
    URL.revokeObjectURL(url);
    showToast(`Downloaded ${selectedFile.name}`);
  };

  const handleDeleteFile = (id: string) => {
    setFiles((prev) => prev.filter((f) => f.id !== id));
    if (selectedFile?.id === id) setSelectedFile(null);
    showToast("File removed from storage");
  };

  return (
    <div className="h-full w-full flex bg-zinc-950 text-zinc-100 overflow-hidden select-none">
      {/* Hidden file input */}
      <input
        ref={fileInputRef}
        type="file"
        onChange={handleFileUpload}
        className="hidden"
      />

      {/* Sidebar navigation */}
      <div className="w-48 bg-zinc-900/60 border-r border-zinc-800/80 p-3 flex flex-col gap-4">
        <div>
          <span className="text-[10px] font-semibold text-zinc-500 uppercase tracking-wider px-2">
            Storage Source
          </span>
          <div className="mt-2 space-y-1">
            <button className="w-full flex items-center gap-2 px-2.5 py-1.5 rounded-lg bg-zinc-800/80 text-zinc-100 text-xs font-medium">
              <HardDrive className="size-3.5 text-blue-400" />
              <span>Workspace Files</span>
            </button>
            <button className="w-full flex items-center gap-2 px-2.5 py-1.5 rounded-lg hover:bg-zinc-800/40 text-zinc-400 hover:text-zinc-200 text-xs transition-colors">
              <Cloud className="size-3.5 text-emerald-400" />
              <span>Cloud Storage</span>
            </button>
          </div>
        </div>

        <div>
          <span className="text-[10px] font-semibold text-zinc-500 uppercase tracking-wider px-2">
            Categories
          </span>
          <div className="mt-2 space-y-1 text-xs text-zinc-400">
            <div className="flex items-center justify-between px-2.5 py-1.5 rounded-lg hover:bg-zinc-800/40">
              <span className="flex items-center gap-2"><Folder className="size-3.5 text-amber-400" /> Folders</span>
              <span className="text-[10px] text-zinc-600">1</span>
            </div>
            <div className="flex items-center justify-between px-2.5 py-1.5 rounded-lg hover:bg-zinc-800/40">
              <span className="flex items-center gap-2"><FileCode className="size-3.5 text-violet-400" /> Scripts</span>
              <span className="text-[10px] text-zinc-600">1</span>
            </div>
            <div className="flex items-center justify-between px-2.5 py-1.5 rounded-lg hover:bg-zinc-800/40">
              <span className="flex items-center gap-2"><FileArchive className="size-3.5 text-pink-400" /> Models</span>
              <span className="text-[10px] text-zinc-600">1</span>
            </div>
          </div>
        </div>

        <div className="mt-auto p-2.5 rounded-xl bg-zinc-900 border border-zinc-800">
          <div className="flex items-center justify-between text-[10px] text-zinc-400 mb-1.5">
            <span>Disk Space</span>
            <span className="text-zinc-200 font-mono">{totalMb} MB used</span>
          </div>
          <div className="h-1.5 w-full bg-zinc-800 rounded-full overflow-hidden">
            <div className="h-full bg-violet-500 rounded-full w-[14%]" />
          </div>
        </div>
      </div>

      {/* Main File Table */}
      <div className="flex-1 flex flex-col">
        {/* Header Search & Actions */}
        <div className="p-3 border-b border-zinc-800 flex items-center justify-between bg-zinc-900/30">
          <div className="flex items-center gap-2 w-64">
            <div className="relative w-full">
              <Search className="size-3.5 text-zinc-500 absolute left-2.5 top-2.5" />
              <Input
                value={searchTerm}
                onChange={(e) => setSearchTerm(e.target.value)}
                placeholder="Search assets & models..."
                className="pl-8 h-8 text-xs bg-zinc-900 border-zinc-800 text-zinc-100"
              />
            </div>
          </div>

          <div className="flex items-center gap-2">
            {notification && (
              <span className="text-[10px] text-emerald-400 font-mono mr-2 animate-in fade-in">
                {notification}
              </span>
            )}
            <Button
              size="xs"
              variant="outline"
              onClick={() => fileInputRef.current?.click()}
              className="border-zinc-800 bg-zinc-900 text-zinc-200 gap-1 text-[11px] hover:border-zinc-700"
            >
              <Upload className="size-3 text-cyan-400" /> Upload File
            </Button>
          </div>
        </div>

        {/* Files Grid */}
        <div className="flex-1 overflow-y-auto p-4">
          <div className="grid grid-cols-2 md:grid-cols-3 gap-3">
            {filtered.map((file) => {
              const isSelected = selectedFile?.id === file.id;
              return (
                <div
                  key={file.id}
                  onClick={() => setSelectedFile(file)}
                  className={`p-3 rounded-xl border cursor-pointer transition-all ${
                    isSelected
                      ? "bg-violet-950/30 border-violet-500/50 shadow-lg shadow-violet-950/20"
                      : "bg-zinc-900/40 border-zinc-800/80 hover:bg-zinc-900/80"
                  }`}
                >
                  <div className="flex items-start justify-between mb-2">
                    {file.type === "folder" ? (
                      <Folder className="size-8 text-amber-400" />
                    ) : file.type === "model" ? (
                      <FileArchive className="size-8 text-pink-400" />
                    ) : file.type === "code" ? (
                      <FileCode className="size-8 text-violet-400" />
                    ) : (
                      <FileText className="size-8 text-blue-400" />
                    )}
                    {file.cloudSynced && (
                      <Badge variant="outline" className="text-[9px] bg-emerald-500/10 text-emerald-400 border-emerald-500/30">
                        Synced
                      </Badge>
                    )}
                  </div>
                  <h4 className="text-xs font-medium text-zinc-200 truncate">{file.name}</h4>
                  <div className="flex items-center justify-between text-[10px] text-zinc-500 mt-2 font-mono">
                    <span>{file.size}</span>
                    <span>{file.modified}</span>
                  </div>
                </div>
              );
            })}
          </div>
        </div>

        {/* Preview & Functional Actions Footer */}
        {selectedFile && (
          <div className="p-3 bg-zinc-900/70 border-t border-zinc-800 flex items-center justify-between text-xs">
            <div className="flex items-center gap-2">
              <span className="text-zinc-400">Selected:</span>
              <span className="text-zinc-100 font-medium">{selectedFile.name}</span>
              <span className="text-zinc-500 font-mono">({selectedFile.size})</span>
            </div>
            <div className="flex items-center gap-2">
              <Button
                size="xs"
                variant="outline"
                onClick={handleDownloadFile}
                className="border-zinc-800 text-zinc-300 hover:text-white text-[11px] gap-1"
              >
                <Download className="size-3" /> Download
              </Button>
              <Button
                size="xs"
                variant="ghost"
                onClick={() => handleDeleteFile(selectedFile.id)}
                className="text-zinc-500 hover:text-rose-400 text-[11px] gap-1"
              >
                <Trash2 className="size-3" />
              </Button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
